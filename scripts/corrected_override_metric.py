"""
Recompute the override metric from the EXISTING audit logs - no Ollama, no
re-run - and write both the legacy and the corrected numbers to
OVERRIDE_METRIC_CORRECTED.md. Published files (README, METRICS.md,
REPORT.html, RESULTS*.md) are not touched.

Legacy:    records whose final decision had llm_matched_policy falsy / all records.
Corrected: of the records where the model produced a valid, in-enum action,
           the share the gate changed (override_rate_of_proposals).

Per record, the LAST terminal event wins (resumed runs re-log records):
gate_decision, unknown_decline_code, diagnosis_failed,
circuit_open_short_circuit or record_processing_error. A gate_decision only
counts as a real proposal if no llm_parse_failure / llm_invalid_action was
logged for that record since its previous terminal event.

Usage: python scripts/corrected_override_metric.py
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TERMINAL = {
    "gate_decision",
    "unknown_decline_code",
    "diagnosis_failed",
    "circuit_open_short_circuit",
    "record_processing_error",
}
NO_PROPOSAL = {"llm_parse_failure", "llm_invalid_action"}

SOURCES = [
    (
        "Subscriptions (RESULTS.md / README / METRICS.md)",
        ROOT / "logs" / "audit_log.jsonl",
        "subscription_id",
    ),
    (
        "One-time payments (RESULTS_ONETIME.md)",
        ROOT / "logs" / "audit_log_onetime.jsonl",
        "payment_id",
    ),
]


def reconstruct(events: list[dict], id_field: str) -> dict[str, dict]:
    """record_id -> {"llm_matched_policy": ..., "llm_proposed": bool} from its last terminal event."""
    pending_failure: dict[str, bool] = {}
    out: dict[str, dict] = {}
    for e in events:
        rid = e.get(id_field)
        if rid is None:
            continue
        et = e.get("event_type")
        if et in NO_PROPOSAL:
            pending_failure[rid] = True
        elif et in TERMINAL:
            proposed = et == "gate_decision" and not pending_failure.get(rid, False)
            matched = e.get("llm_matched_policy") if et == "gate_decision" else False
            out[rid] = {"llm_matched_policy": matched, "llm_proposed": proposed}
            pending_failure[rid] = False
    return out


def _load(path: Path) -> list[dict]:
    rows = []
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.strip():
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
    return rows


def render(sources=SOURCES) -> str:
    sys.path.insert(0, str(ROOT / "src"))
    from failsafe.recovery_pipeline import override_metrics

    lines = [
        "# Override metric - corrected (recomputed from existing audit logs)",
        "",
        "Generated by `scripts/corrected_override_metric.py` from the audit logs",
        "already in `logs/` - no model was re-run. The legacy metric counts records",
        "where the LLM never produced a usable proposal (unknown decline code,",
        "diagnosis failure, parse failure, invalid action, open circuit, crash) as",
        '"overrides". The corrected metric divides only over real proposals.',
        "Published numbers elsewhere use the legacy metric.",
        "",
        "| Run | Legacy override rate | Corrected: override_rate_of_proposals | No usable proposal |",
        "|---|---|---|---|",
    ]
    for label, path, id_field in sources:
        if not path.exists():
            lines.append(f"| {label} | (no log at {path.name}) | - | - |")
            continue
        rows = list(reconstruct(_load(path), id_field).values())
        m = override_metrics(rows)
        lines.append(
            f"| {label} | {m['overridden']}/{m['total']} ({m['override_rate'] * 100:.1f}%) "
            f"| {m['overridden_proposals']}/{m['proposals']} ({m['override_rate_of_proposals'] * 100:.1f}%) "
            f"| {m['no_proposal']} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    out = ROOT / "OVERRIDE_METRIC_CORRECTED.md"
    out.write_text(render(), encoding="utf-8")
    print(out.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
